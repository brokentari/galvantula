// Package standards renders the rules that every agent follows, for this
// repo and for each product, from pinned copies of three skills:
// ponytail (least code), go-modern-guidelines (modern Go) and orwell-writing
// (plain English). vendor.sh downloads them; vendor/lock.json pins them.
package standards

import (
	"bytes"
	"embed"
	"encoding/json"
	"errors"
	"fmt"
	"strconv"
	"strings"
)

//go:embed all:vendor
var vendor embed.FS

const (
	Begin = "<!-- BEGIN STANDARDS: generated by `go run ./cmd/factory standards`; edit standards/ instead -->"
	End   = "<!-- END STANDARDS -->"
)

const precedence = `## Standards

These rules come from three pinned skills (see ` + "`standards/vendor/lock.json`" + `). When they disagree, the first one wins:

1. The tests and the contract.
2. Ponytail's never-cut list: validation at trust boundaries, error handling that prevents data loss, security.
3. The modern Go guidelines. Skip one only if it would not compile or would change behavior, and say why.
4. Ponytail's smallest complete change.
5. Orwell, for prose only. Code, identifiers, commands and Go conventions (error strings start in lower case and have no final period) stay as they are.
`

type guideline struct {
	ID         string `json:"id"`
	Since      string `json:"since_version"`
	Modernizer bool   `json:"modernizer"`
	Guideline  string `json:"guideline"`
}

// Render returns the standards block for a product or repo that targets goVersion (such as "1.27").
func Render(goVersion string) (string, error) {
	target, err := minor(goVersion)
	if err != nil {
		return "", err
	}
	raw, err := vendor.ReadFile("vendor/go-modern/internal/guidelines/guidelines.json")
	if err != nil {
		return "", err
	}
	var all []guideline
	if err := json.Unmarshal(raw, &all); err != nil {
		return "", fmt.Errorf("guidelines.json: %w", err)
	}
	var checked int
	var guidance []string
	for _, g := range all {
		since, err := minor(g.Since)
		if err != nil {
			return "", fmt.Errorf("guideline %s: %w", g.ID, err)
		}
		switch {
		case since > target:
		case g.Modernizer:
			checked++
		default:
			guidance = append(guidance, fmt.Sprintf("- `%s` (Go %s): %s", g.ID, g.Since, g.Guideline))
		}
	}

	ponytail, err := skill("vendor/ponytail/.agents/rules/ponytail.md")
	if err != nil {
		return "", err
	}
	orwell, err := skill("vendor/orwell/skills/orwell-writing/SKILL.md")
	if err != nil {
		return "", err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "%s\n%s\n", Begin, precedence)
	fmt.Fprintf(&b, "### Modern Go (Go %s)\n\n", goVersion)
	fmt.Fprintf(&b, "`go fix -diff ./...` must print nothing. It checks %d of the guidelines. No tool checks these %d, so follow them yourself:\n\n", checked, len(guidance))
	fmt.Fprintf(&b, "%s\n\n%s\n%s\n%s\n", strings.Join(guidance, "\n"), ponytail, orwell, End)
	return b.String(), nil
}

// Replace swaps the standards block in doc for block. doc must hold both markers.
func Replace(doc []byte, block string) ([]byte, error) {
	i := bytes.Index(doc, []byte(Begin))
	j := bytes.Index(doc, []byte(End))
	if i < 0 || j < i {
		return nil, errors.New("no standards block: add the BEGIN and END STANDARDS markers first")
	}
	return bytes.Join([][]byte{doc[:i], []byte(strings.TrimSuffix(block, "\n")), doc[j+len(End):]}, nil), nil
}

// Review returns the ponytail-review skill, which review nodes and phase
// reviews follow.
func Review() (string, error) {
	return skill("vendor/ponytail/skills/ponytail-review/SKILL.md")
}

// skill reads a vendored markdown file without its front matter and moves
// its headings two levels down, so they sit under "## Standards".
func skill(path string) (string, error) {
	raw, err := vendor.ReadFile(path)
	if err != nil {
		return "", err
	}
	text := string(raw)
	if rest, ok := strings.CutPrefix(text, "---\n"); ok {
		if _, body, ok := strings.Cut(rest, "\n---\n"); ok {
			text = body
		}
	}
	var out []string
	fenced := false
	for line := range strings.Lines(strings.TrimSpace(text)) {
		if strings.HasPrefix(line, "```") {
			fenced = !fenced
		}
		if !fenced && strings.HasPrefix(line, "#") {
			line = "##" + line
		}
		out = append(out, line)
	}
	return strings.Join(out, "") + "\n", nil
}

// minor returns the minor number of a Go version such as "1.27".
func minor(v string) (int, error) {
	rest, ok := strings.CutPrefix(v, "1.")
	n, err := strconv.Atoi(rest)
	if !ok || err != nil {
		return 0, fmt.Errorf("go version %q must look like 1.27", v)
	}
	return n, nil
}
