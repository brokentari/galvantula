// Command gen-ts writes TypeScript types for the event log and the API, so
// the UI and the runtime share one schema. Run it with go generate ./...
package main

import (
	"cmp"
	"encoding/json/jsontext"
	"flag"
	"fmt"
	"log"
	"maps"
	"os"
	"reflect"
	"slices"
	"strings"
	"time"

	"github.com/brokentari/galvantula/internal/event"
	"github.com/brokentari/galvantula/internal/graph"
	"github.com/brokentari/galvantula/internal/server"
)

func main() {
	out := flag.String("o", "", "output file; stdout if empty")
	flag.Parse()
	src := generate()
	if *out == "" {
		fmt.Print(src)
		return
	}
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		log.Fatal(err)
	}
}

func strs[T ~string](vs ...T) []string {
	out := make([]string, len(vs))
	for i, v := range vs {
		out[i] = string(v)
	}
	return out
}

// enums lists the values of each Go string type that the UI sees as a union.
var enums = map[reflect.Type][]string{
	reflect.TypeFor[graph.Kind]():         strs(graph.Kinds...),
	reflect.TypeFor[event.Type]():         strs(slices.Sorted(maps.Keys(event.Payloads))...),
	reflect.TypeFor[event.NodeStatus]():   strs(event.Pending, event.Running, event.Waiting, event.Succeeded, event.Failed),
	reflect.TypeFor[event.RunStatus]():    strs(event.RunRunning, event.RunSucceeded, event.RunFailed),
	reflect.TypeFor[event.FailureClass](): strs(event.Task, event.Infra, event.Limit),
}

// renames avoids vague names in TypeScript.
var renames = map[reflect.Type]string{
	reflect.TypeFor[event.Type]():  "EventType",
	reflect.TypeFor[event.Event](): "LogEvent", // Event and Node clash with DOM globals
	reflect.TypeFor[graph.Node]():  "GraphNode",
}

type gen struct{ decls map[string]string }

func generate() string {
	g := gen{decls: map[string]string{}}
	g.ts(reflect.TypeFor[event.Event]())
	g.ts(reflect.TypeFor[event.RunSummary]())
	g.ts(reflect.TypeFor[server.DecideRequest]())
	g.ts(reflect.TypeFor[event.NodeStatus]())

	var union strings.Builder
	union.WriteString("export type FactoryEvent = Omit<LogEvent, \"type\" | \"data\"> & (\n")
	for _, t := range slices.Sorted(maps.Keys(event.Payloads)) {
		data := "data?: undefined"
		if p := event.Payloads[t]; p != nil {
			data = "data: " + g.ts(reflect.TypeOf(p))
		}
		fmt.Fprintf(&union, "  | { type: %q; %s }\n", t, data)
	}
	union.WriteString(");\n")

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gen-ts. DO NOT EDIT.\n")
	for _, name := range slices.Sorted(maps.Keys(g.decls)) {
		b.WriteString("\n" + g.decls[name])
	}
	b.WriteString("\n" + union.String())
	return b.String()
}

func name(t reflect.Type) string {
	if n, ok := renames[t]; ok {
		return n
	}
	return t.Name()
}

func (g gen) ts(t reflect.Type) string {
	if vals, ok := enums[t]; ok {
		n := name(t)
		quoted := make([]string, len(vals))
		for i, v := range vals {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		g.decls[n] = fmt.Sprintf("export type %s = %s;\n", n, strings.Join(quoted, " | "))
		return n
	}
	switch t {
	case reflect.TypeFor[time.Time]():
		return "string"
	case reflect.TypeFor[jsontext.Value]():
		return "unknown"
	}
	switch t.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Float64:
		return "number"
	case reflect.Slice:
		return g.ts(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + g.ts(t.Elem()) + ">"
	case reflect.Pointer:
		return g.ts(t.Elem())
	case reflect.Struct:
		n := name(t)
		if n == "" {
			panic("gen-ts: name this struct type; TypeScript needs a name: " + t.String())
		}
		if _, done := g.decls[n]; done {
			return n
		}
		g.decls[n] = "" // reserve the name first, in case the type refers to itself
		var b strings.Builder
		fmt.Fprintf(&b, "export interface %s {\n", n)
		for f := range t.Fields() {
			field, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
			if field == "-" || !f.IsExported() {
				continue
			}
			optional := ""
			if strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero") {
				optional = "?"
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", cmp.Or(field, f.Name), optional, g.ts(f.Type))
		}
		b.WriteString("}\n")
		g.decls[n] = b.String()
		return n
	}
	panic("gen-ts: unsupported type " + t.String())
}
